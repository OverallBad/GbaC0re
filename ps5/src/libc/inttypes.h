/* Freestanding <inttypes.h>: fixed-width typedefs come from gcc's
   freestanding <stdint.h>; the PRI* macros below are the LP64 set
   (x86-64: int=32 bit, long/pointer=64 bit), which is what mGBA's
   "%" PRIi32 / PRIXPTR uses expand to. */
